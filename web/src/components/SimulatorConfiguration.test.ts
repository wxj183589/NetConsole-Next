import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import SimulatorConfiguration from './SimulatorConfiguration.vue'

const api = vi.hoisted(() => ({ captureCompleteConfiguration: vi.fn(), changeSimulatorDescription: vi.fn(), compareCompleteConfigurations: vi.fn(), previewCompleteConfigurationRestore: vi.fn(), verifyNativeCheckpointRestore: vi.fn(), getNativeCheckpointOperations: vi.fn(), getCompleteConfigurations: vi.fn(), getCompleteConfigurationView: vi.fn(), getSimulatorConfigurationChanges: vi.fn() }))
vi.mock('../api/client', () => api)
const backup = { id: 'complete-a', profileId: 'a', capturedMs: 1000, integrity: 'VERIFIED', restorable: true }
const comparison = { before: backup, after: { ...backup, id: 'complete-b' }, originalConfigurationChanged: true, sensitiveValuesChanged: true, addedLines: 1, removedLines: 1, truncated: false, contexts: [{ context: 'interface GigabitEthernet1/0/1', categories: ['INTERFACE'], addedLines: 1, removedLines: 1, sensitiveValuesChanged: false, truncated: false, lines: [{ kind: 'REMOVED', text: ' description before' }, { kind: 'ADDED', text: ' description after' }] }, { context: 'vlan 10', categories: ['VLAN'], addedLines: 1, removedLines: 0, sensitiveValuesChanged: false, truncated: false, lines: [{ kind: 'ADDED', text: 'vlan 10' }] }] }
function render() { return mount(SimulatorConfiguration, { props: { profileId: 'a' }, global: { stubs: { 'el-button': { template: '<button><slot /></button>' } } } }) }
function button(wrapper: ReturnType<typeof render>, name: string) { return wrapper.findAll('button').find(item => item.text() === name)! }
describe('simulator configuration changes', () => {
  beforeEach(() => { vi.resetAllMocks(); api.getCompleteConfigurations.mockResolvedValue([backup]); api.getSimulatorConfigurationChanges.mockResolvedValue([]); api.getNativeCheckpointOperations.mockResolvedValue([]); api.changeSimulatorDescription.mockResolvedValue({ state: 'VERIFIED' }) })
  it('requires a verified baseline and explicit confirmation before writing', async () => {
    const wrapper = render()
    expect(api.captureCompleteConfiguration).not.toHaveBeenCalled()
    expect(button(wrapper, '执行接口描述变更').attributes('disabled')).toBeDefined()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    await wrapper.get('input[placeholder="GigabitEthernet1/0/1"]').setValue('GigabitEthernet1/0/1')
    await wrapper.get('input[maxlength="80"]').setValue('test-description')
    expect(button(wrapper, '执行接口描述变更').attributes('disabled')).toBeDefined()
    await wrapper.findAll('input[type="checkbox"]')[1].setValue(true)
    await button(wrapper, '执行接口描述变更').trigger('click'); await flushPromises()
    expect(api.changeSimulatorDescription).toHaveBeenCalledWith({ profileId: 'a', expectedBackupId: 'complete-a', interfaceName: 'GigabitEthernet1/0/1', description: 'test-description' })
    expect(button(wrapper, '执行接口描述变更').attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
  it('discards a previous device response and clears confirmation on context change', async () => {
    let resolve!: (value: unknown) => void
    api.getCompleteConfigurations.mockReturnValueOnce(new Promise(done => { resolve = done }))
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click')
    await wrapper.setProps({ profileId: 'b' })
    resolve([backup]); await flushPromises()
    expect(wrapper.get('select[aria-label="完整配置基线"]').findAll('option')).toHaveLength(1)
    expect(button(wrapper, '执行接口描述变更').attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
  it('never selects an incomplete backup for a write baseline', async () => {
    api.getCompleteConfigurations.mockResolvedValue([{ ...backup, restorable: false }])
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    expect(wrapper.get('select').element.value).toBe('')
    expect(wrapper.findAll('option')[1].attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
  it('revokes a previously selected baseline when its device identity is no longer restorable', async () => {
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    await wrapper.findAll('input[type="checkbox"]')[1].setValue(true)
    api.getCompleteConfigurations.mockResolvedValue([{ ...backup, restorable: false }])
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    expect((wrapper.get('select[aria-label="完整配置基线"]').element as HTMLSelectElement).value).toBe('')
    expect((wrapper.findAll('input[type="checkbox"]')[1].element as HTMLInputElement).checked).toBe(false)
    expect(button(wrapper, '执行接口描述变更').attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
  it('compares independent historical selections and filters contextual changes', async () => {
    api.getCompleteConfigurations.mockResolvedValue([backup, { ...backup, id: 'complete-b' }])
    api.compareCompleteConfigurations.mockResolvedValue(comparison)
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    await wrapper.get('select[aria-label="比较源备份"]').setValue('complete-a')
    await wrapper.get('select[aria-label="比较目标备份"]').setValue('complete-b')
    await button(wrapper, '比较完整配置').trigger('click'); await flushPromises()
    expect(api.compareCompleteConfigurations).toHaveBeenCalledWith('complete-a', 'complete-b')
    expect(wrapper.text()).toContain('敏感值存在变化（已隐藏）')
    expect(wrapper.findAll('article')).toHaveLength(2)
    await wrapper.get('select[aria-label="比较配置分类"]').setValue('INTERFACE')
    expect(wrapper.findAll('article')).toHaveLength(1)
    expect(wrapper.get('article').text()).toContain('interface GigabitEthernet1/0/1')
    await wrapper.get('select[aria-label="比较目标备份"]').setValue('complete-a')
    expect(wrapper.find('[aria-label="配置比较结果"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('captures the live configuration for a read-only restore preview without writing', async () => {
    api.getCompleteConfigurations.mockResolvedValue([backup, { ...backup, id: 'current' }])
    api.previewCompleteConfigurationRestore.mockResolvedValue({ backupId: backup.id, currentBackupId: 'current', compatible: true, writeAllowed: false, blockers: ['FULL_DEVICE_RESTORE_NOT_IMPLEMENTED'], comparison })
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    await button(wrapper, '读取当前配置并预览恢复').trigger('click'); await flushPromises()
    expect(api.previewCompleteConfigurationRestore).toHaveBeenCalledWith(backup.id)
    expect(wrapper.text()).toContain('WRITE_ALLOWED=false')
    expect(wrapper.text()).toContain('FULL_DEVICE_RESTORE_NOT_IMPLEMENTED')
    expect(api.changeSimulatorDescription).not.toHaveBeenCalled()
    expect((wrapper.get('select[aria-label="比较源备份"]').element as HTMLSelectElement).value).toBe('current')
    wrapper.unmount()
  })
  it('clears a read-only preview and write confirmation when the selected baseline changes', async () => {
    api.getCompleteConfigurations.mockResolvedValue([backup, { ...backup, id: 'complete-b' }])
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    await wrapper.findAll('input[type="checkbox"]')[1].setValue(true)
    await wrapper.get('select[aria-label="完整配置基线"]').setValue('complete-b')
    expect((wrapper.findAll('input[type="checkbox"]')[1].element as HTMLInputElement).checked).toBe(false)
    wrapper.unmount()
  })
  it('shows comparison failure and ignores a stale response from a previous device', async () => {
    api.compareCompleteConfigurations.mockRejectedValueOnce(new Error('备份完整性校验失败'))
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    await button(wrapper, '比较完整配置').trigger('click'); await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toBe('备份完整性校验失败')
    let resolve!: (value: unknown) => void
    api.compareCompleteConfigurations.mockReturnValueOnce(new Promise(done => { resolve = done }))
    await button(wrapper, '比较完整配置').trigger('click')
    await wrapper.setProps({ profileId: 'b' })
    resolve(comparison); await flushPromises()
    expect(wrapper.find('[aria-label="配置比较结果"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('downloads only the freshly verified redacted configuration', async () => {
    api.getCompleteConfigurationView.mockResolvedValue({ backup, redactedConfiguration: '#\n password <REDACTED>\nreturn' })
    const create = vi.fn(() => 'blob:fixture'); const revoke = vi.fn()
    vi.stubGlobal('URL', { createObjectURL: create, revokeObjectURL: revoke })
    const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    await button(wrapper, '下载脱敏完整配置').trigger('click'); await flushPromises()
    expect(api.getCompleteConfigurationView).toHaveBeenCalledWith(backup.id)
    expect(create).toHaveBeenCalledOnce()
    expect(click).toHaveBeenCalledOnce()
    expect(api.changeSimulatorDescription).not.toHaveBeenCalled()
    wrapper.unmount(); click.mockRestore(); vi.unstubAllGlobals()
  })
  it('exports the selected sanitized comparison with metadata and truncation evidence', async () => {
    const report = { ...comparison, truncated: true }
    api.compareCompleteConfigurations.mockResolvedValue(report)
    const create = vi.fn(() => 'blob:comparison')
    vi.stubGlobal('URL', { createObjectURL: create, revokeObjectURL: vi.fn() })
    const parts: BlobPart[][] = []
    vi.stubGlobal('Blob', class { constructor(value: BlobPart[]) { parts.push(value) } })
    let filename = ''
    const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(function (this: HTMLAnchorElement) { filename = this.download })
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    await button(wrapper, '比较完整配置').trigger('click'); await flushPromises()
    await button(wrapper, '导出脱敏比较报告').trigger('click')
    expect(filename).toBe('configuration-diff-complete-a-complete-b.json')
    expect(JSON.parse(String(parts[0]![0]))).toEqual(report)
    expect(create).toHaveBeenCalledOnce()
    expect(api.changeSimulatorDescription).not.toHaveBeenCalled()
    wrapper.unmount(); click.mockRestore(); vi.unstubAllGlobals()
  })
  it('requires independent confirmation for native checkpoint restoration and displays its evidence', async () => {
    api.getCompleteConfigurations.mockResolvedValue([{ ...backup, host: '192.168.56.3', model: 'S6850' }])
    const wrapper = render()
    await button(wrapper, '刷新完整备份').trigger('click'); await flushPromises()
    expect(button(wrapper, '执行原生检查点恢复验证').attributes('disabled')).toBeDefined()
    await wrapper.get('input[placeholder="GigabitEthernet1/0/1"]').setValue('GigabitEthernet1/0/48')
    await wrapper.get('input[maxlength="80"]').setValue('R70-controlled-test')
    await wrapper.get('input[aria-label="确认原生检查点恢复验证"]').setValue(true)
    api.getNativeCheckpointOperations.mockResolvedValue([{ id: 'op', interfaceName: 'GigabitEthernet1/0/48', state: 'SERVICE_VERIFIED', checkpointId: '1000000001', configWriteSucceeded: true, configReadbackVerified: true, serviceVerified: true, rollbackVerified: false, serviceVerificationScope: 'INTERFACE_LINK_PROTOCOL_AND_LLDP_NEIGHBORS' }])
    await button(wrapper, '执行原生检查点恢复验证').trigger('click'); await flushPromises()
    expect(api.verifyNativeCheckpointRestore).toHaveBeenCalledWith({ profileId: 'a', expectedBackupId: backup.id, interfaceName: 'GigabitEthernet1/0/48', description: 'R70-controlled-test' })
    expect(wrapper.get('[aria-label="检查点恢复记录"]').text()).toContain('CONFIG_READBACK_VERIFIED=true')
    expect(wrapper.get('[aria-label="检查点恢复记录"]').text()).toContain('ROLLBACK_VERIFIED=false')
    expect(button(wrapper, '执行原生检查点恢复验证').attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
})
